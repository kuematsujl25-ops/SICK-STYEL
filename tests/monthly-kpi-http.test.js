import {test} from 'node:test';
import assert from 'node:assert/strict';
import {spawn} from 'node:child_process';
import {mkdtemp,rm} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import path from 'node:path';

test('authenticated KPI HTTP save/read/backup/restore retain evidence and reject unsafe writes',async t=>{
 const dir=await mkdtemp(path.join(tmpdir(),'sickstyle-kpi-http-'));
 const proc=spawn(process.execPath,['server.js'],{env:{...process.env,PORT:'0',DATA_DIR:dir,SETUP_TOKEN:'synthetic-kpi-setup'},stdio:['ignore','pipe','pipe']});
 t.after(async()=>{if(proc.exitCode===null)await new Promise(resolve=>{proc.once('exit',resolve);proc.kill();});await rm(dir,{recursive:true,force:true});});
 let output='';const base=await new Promise((resolve,reject)=>{proc.stdout.on('data',b=>{output+=b;const m=output.match(/http:\/\/127.0.0.1:\d+/);if(m)resolve(m[0]);});proc.on('error',reject);proc.on('exit',c=>reject(Error('Server exit '+c)));});
 let cookie='';
 const req=async(route,method='GET',data,headers={})=>{const res=await fetch(base+'/api/'+route,{method,headers:{Cookie:cookie,'Content-Type':'application/json',...headers},body:data?JSON.stringify(data):undefined});return {status:res.status,data:await res.json(),cookie:res.headers.get('set-cookie')};};
 assert.equal((await req('data','PUT',{})).status,401);
 assert.equal((await req('backup')).status,401);
 assert.equal((await req('restore','POST',{})).status,401);
 const signup=await req('setup','POST',{email:'owner@example.com',password:'Synthetic-kpi-password',setupToken:'synthetic-kpi-setup'});assert.equal(signup.status,200);cookie=signup.cookie.split(';')[0];
 const oldBackup=(await req('backup')).data;
 const today=new Date().toLocaleDateString('sv-SE',{timeZone:'Asia/Tokyo'});
 const future=new Date(Date.parse(today)+86400000).toISOString().slice(0,10);
 const record={id:'dm-1',title:'Synthetic evidence',type:'dm',date:today,party:'synthetic-party',deal:'',ref:'',channel:'unknown',amount:null,qty:null,createdAt:new Date().toISOString()};
 let data=(await req('data')).data;data.salesKpiRecords=[record];
 assert.equal((await req('data','PUT',data,{Origin:'https://evil.example'})).status,403);
 const save=await req('data','PUT',data);assert.equal(save.status,200);const stale=structuredClone(data);
 data=(await req('data')).data;assert.deepEqual(data.salesKpiRecords,[record]);
 assert.equal((await req('data','PUT',stale)).status,409);
 const oldClient=structuredClone(data);delete oldClient.salesKpiRecords;
 assert.equal((await req('data','PUT',oldClient)).status,400);
 const tampered=structuredClone(data);tampered.salesKpiRecords[0].title='Edited evidence';assert.equal((await req('data','PUT',tampered)).status,400);
 assert.equal((await req('data','PUT',{...data,salesKpiRecords:[record,{...record,id:'future',date:future}]})).status,400);
 const cancellation={...record,id:'void-1',type:'void',ref:record.id,date:future};
 assert.equal((await req('data','PUT',{...data,salesKpiRecords:[record,cancellation]})).status,400);
 assert.deepEqual((await req('data')).data.salesKpiRecords,[record]);
 cancellation.date=today;
 assert.equal((await req('data','PUT',{...data,salesKpiRecords:[record,cancellation]})).status,200);
 data=(await req('data')).data;
 const backup=(await req('backup')).data;assert.deepEqual(backup.data.salesKpiRecords,[record,cancellation]);
 assert.equal((await req('restore','POST',{...oldBackup,revision:data.revision-1})).status,409);
 assert.equal((await req('restore','POST',{...oldBackup,revision:data.revision})).status,200);
 data=(await req('data')).data;assert.deepEqual(data.salesKpiRecords,[record,cancellation]);
 const corrected={...record,id:'dm-corrected',title:'Corrected synthetic evidence'};
 assert.equal((await req('data','PUT',{...data,salesKpiRecords:[...data.salesKpiRecords,corrected]})).status,200);
 data=(await req('data')).data;
 assert.equal((await req('restore','POST',{...backup,revision:data.revision})).status,200);
 assert.deepEqual((await req('data')).data.salesKpiRecords,[record,cancellation,corrected]);
 assert.equal((await req('logout','POST',{})).status,200);
 assert.equal((await req('data','PUT',data)).status,401);
});
