import {test} from 'node:test';
import assert from 'node:assert/strict';
import {spawn} from 'node:child_process';
import {mkdtemp,rm} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import path from 'node:path';
test('Metricool snapshots require admin session and same origin, and never modify workspace or publish',async t=>{
 const dir=await mkdtemp(path.join(tmpdir(),'ig-review-http-'));
 const proc=spawn(process.execPath,['server.js'],{env:{...process.env,PORT:'0',DATA_DIR:dir,SETUP_TOKEN:'synthetic-ig-review'},stdio:['ignore','pipe','inherit']});
 t.after(async()=>{if(proc.exitCode===null)await new Promise(r=>{proc.once('exit',r);proc.kill();});await rm(dir,{recursive:true,force:true});});
 let out='';const base=await new Promise((resolve,reject)=>{proc.stdout.on('data',b=>{out+=b;const m=out.match(/http:\/\/127\.0\.0\.1:\d+/);if(m)resolve(m[0]);});proc.on('error',reject);proc.on('exit',c=>reject(Error('server exit '+c)));});
 const route=base+'/api/instagram/metricool-review';
 const req=(method,headers={},value)=>fetch(route,{method,headers:{'Content-Type':'application/json',...headers},body:value===undefined?undefined:JSON.stringify(value)});
 const snapshot={version:1,source:'metricool',account:'demo_business',observedAt:'2026-01-02T00:00:00Z',analysis:null,planner:{from:'2026-01-02T00:00:00Z',to:'2026-02-01T00:00:00Z',posts:[]}};
 assert.equal((await req('GET')).status,401);assert.equal((await req('PUT',{Origin:base},{snapshot,revision:null})).status,401);
 const setup=await fetch(base+'/api/setup',{method:'POST',headers:{'Content-Type':'application/json'},body:JSON.stringify({email:'review@example.com',password:'Synthetic-review-password',setupToken:'synthetic-ig-review'})});
 assert.equal(setup.status,200);const Cookie=setup.headers.get('set-cookie').split(';')[0];const headers={Cookie,Origin:base};
 const workspace=async()=>await(await fetch(base+'/api/data',{headers})).json();
 const before=await workspace();
 assert.deepEqual(await(await req('GET',headers)).json(),{snapshot:null,revision:null});
 assert.equal((await req('PUT',{Cookie},{snapshot,revision:null})).status,403);
 assert.equal((await req('PUT',{Cookie,Origin:'https://other.example.com'},{snapshot,revision:null})).status,403);
 assert.equal((await req('PUT',headers,{snapshot,revision:null,padding:'x'.repeat(65_000)})).status,413);
 assert.equal((await req('POST',headers,{snapshot,revision:null})).status,405);
 assert.equal((await req('PUT',headers,{snapshot,revision:null})).status,200);
 assert.equal((await req('PUT',headers,{snapshot,revision:null})).status,409);
 const saved=await req('GET',headers);assert.equal(saved.headers.get('cache-control'),'no-store');
 assert.deepEqual((await saved.json()).snapshot.planner.posts,[]);
 assert.deepEqual(await workspace(),before);
 const publicResponse=await(await fetch(base+'/api/public/site')).text();assert.doesNotMatch(publicResponse,/demo_business|metricool/);
});
