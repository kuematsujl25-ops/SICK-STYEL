// Build a distributable, pure catalog from the existing SICK STYLE definitions.
import {readFileSync,writeFileSync} from 'node:fs';
import {createHash} from 'node:crypto';
const source=process.argv[2]||'../comparison-kpi-dashboard/ai-coo/sickstyle/skills.json';
const raw=readFileSync(source,'utf8'),data=JSON.parse(raw);
if(data.business_unit!=='sickstyle'||data.skills.length!==9)throw Error('SICK STYLEの既存9専門機能が必要です');
const roles=data.skills.map(s=>({id:s.id,agents:s.agents,mission:s.mission,expertise:s.expertise,inputs:s.inputs,workflow:s.workflow,outputRequirements:s.output_schema,quality:s.quality_criteria}));
writeFileSync('public/ai-catalog.js','// Generated by scripts/ai-staff/sync-catalog.js; source SHA256: '+createHash('sha256').update(raw).digest('hex')+'\nexport const TEAM_CATALOG='+JSON.stringify(roles,null,2)+';\n');
console.log('Existing SICK STYLE specialist definitions synchronized: '+roles.length);
